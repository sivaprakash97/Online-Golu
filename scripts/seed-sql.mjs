// Prints supabase/seed.sql from src/data/seed.js so the demo Bommais live in one place.
import { SEED_BOMMAIS } from '../src/data/seed.js'

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`
const rows = SEED_BOMMAIS.map(
  (b) =>
    `  (${q(b.name)}, ${q(b.body)}, ${q(b.skin_tone)}, ${q(b.hair)}, ${q(b.hair_color)}, ${q(b.outfit)}, ${q(b.outfit_color)}, ${q(b.face)}, ${arr(b.face_extras)}, ${q(b.accessory)}, ${q(b.pose)}, ${b.step}, true, ${q(b.created_at)}::timestamptz)`,
)
console.log(`-- Fictional demo Bommais (generated by \`npm run seed:sql\`). Safe to re-run: skips if already seeded.
insert into public.bommais (name, body, skin_tone, hair, hair_color, outfit, outfit_color, face, face_extras, accessory, pose, step, seeded, created_at)
select * from (values
${rows.join(',\n')}
) as v
where not exists (select 1 from public.bommais where seeded);`)
